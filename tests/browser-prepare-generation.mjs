import assert from "node:assert/strict";
import { chromium } from "playwright";
const browser = await chromium.launch({ executablePath: "C:/Program Files/Google/Chrome/Application/chrome.exe", headless: true });
const context = await browser.newContext({ extraHTTPHeaders: { "X-Composer-Test": "1" } });
const app = await context.newPage(); app.setDefaultTimeout(6000);
let source, generationCalls = 0, state = "drafting";
try {
  await context.route("**/api/settings", route => route.fulfill({ json: { provider: "codex" } }));
  await context.route("**/api/state", route => route.fulfill({ json: { capture: null, fillResult: null } }));
  await context.route("**/api/capture", route => { source = route.request().postDataJSON(); return route.fulfill({ json: source }); });
  await context.route("**/api/generate", route => { generationCalls++; assert.equal(route.request().postDataJSON().capture.id, source.id); return route.fulfill({ json: { id: "qa-prepare" } }); });
  await context.route("**/api/jobs/qa-prepare", route => route.fulfill({ json: state === "complete" ? { state, draft: { answers: source.fields.map(field => ({ fieldId: field.id, value: /subject/i.test(field.label) ? "CMS PARTNER" : /message/i.test(field.label) ? "Hey! I can build your Next.js and Supabase CMS. Here is a relevant project: https://example.com/demo" : "", reason: "Browser fixture", needsInput: false })), notes: [], review: { eligibility: "fit", summary: "Questions and keywords checked.", questionsCovered: [], keywordsChecked: ["CMS PARTNER"], warnings: [] } } } : { state: "running", stage: state } }));
  await app.goto("http://127.0.0.1:32187/?platform=onlinejobs");
  await app.getByLabel("Job title", { exact: true }).fill("CMS developer");
  await app.getByLabel("Job description", { exact: true }).fill("Build a Next.js and Supabase CMS. Include CMS PARTNER.");
  await app.getByRole("button", { name: "Prepare application", exact: true }).click();
  await app.getByRole("button", { name: "Generating application…", exact: true }).waitFor();
  assert.equal(await app.getByRole("button", { name: "Generating application…", exact: true }).isDisabled(), true);
  assert.equal(await app.getByLabel("Job description", { exact: true }).isDisabled(), true);
  assert.equal(generationCalls, 1);
  state = "reviewing";
  await app.locator(".source-panel").getByRole("button", { name: "Reviewing application…", exact: true }).waitFor();
  state = "complete";
  await app.getByText("Reviewed for this job", { exact: true }).waitFor();
  assert.equal(await app.getByLabel("Answer for Application subject", { exact: true }).inputValue(), "CMS PARTNER");
  assert.match(await app.getByLabel("Answer for Application message", { exact: true }).inputValue(), /https:\/\/example.com\/demo/);
  assert.equal(await app.getByRole("button", { name: "Prepare application", exact: true }).isEnabled(), true);
  assert.equal(generationCalls, 1);
  await app.getByRole("button", { name: "Paste a draft", exact: true }).click();
  await app.getByLabel("Paste your application draft", { exact: true }).fill("My pasted answer must not be applied during generation.");
  state = "drafting";
  await app.getByRole("button", { name: "Regenerate", exact: true }).click();
  assert.equal(await app.getByLabel("Paste your application draft", { exact: true }).isDisabled(), true);
  assert.equal(await app.getByRole("combobox", { name: "Target field", exact: true }).isDisabled(), true);
  assert.equal(await app.getByRole("button", { name: "Use this answer", exact: true }).isDisabled(), true);
  state = "complete";
  await app.getByRole("button", { name: "Regenerate", exact: true }).waitFor();
  assert.equal(generationCalls, 2);
  console.log("PASS: Prepare immediately generates the new capture, displays generating/reviewing states, locks inputs, and shows reviewed answers.");
} finally { await context.close(); await browser.close(); }
