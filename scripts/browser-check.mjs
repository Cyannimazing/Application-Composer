import assert from "node:assert/strict";
import { chromium } from "playwright";
import { readFile, writeFile, mkdir, cp, mkdtemp } from "node:fs/promises";
import path from "node:path";
import http from "node:http";
process.env.PLAYWRIGHT_BROWSERS_PATH ||= path.resolve(".local/browsers");
const output = path.resolve("output/playwright");
await mkdir(output, { recursive: true });
const qaExtension = path.resolve(".local/qa-extension");
await cp("extension", qaExtension, { recursive: true });
const backgroundPath = path.join(qaExtension, 'background.js');
await writeFile(backgroundPath, (await readFile(backgroundPath, 'utf8')).replace('"X-Composer-Key": pairingKey', '"X-Composer-Key": pairingKey, "X-Composer-Test": "1"'));
const manifest = JSON.parse(await readFile(path.join(qaExtension, "manifest.json"), "utf8"));
// Grant only the local fixture origin for automation; the shipped extension retains activeTab only.
manifest.host_permissions.push("http://127.0.0.1:32188/*");
await writeFile(path.join(qaExtension, "manifest.json"), JSON.stringify(manifest));
const formHtml = await readFile("public/practice-form.html");
const formTools = await readFile("extension/form-tools.js");
const fixture = http.createServer((req, res) => { res.setHeader("Content-Type", req.url === "/form-tools.js" ? "text/javascript" : "text/html"); res.end(req.url === "/form-tools.js" ? formTools : formHtml); });
await new Promise((resolve, reject) => { fixture.once("error", reject); fixture.listen(32188, "127.0.0.1", resolve); });
const executable = path.resolve(".local/browsers/chromium-1248/chrome-win64/chrome.exe");
const context = await chromium.launchPersistentContext(await mkdtemp(path.resolve(".local/qa-browser-")), { executablePath: executable, headless: true, viewport: { width: 1440, height: 1000 }, args: [`--disable-extensions-except=${qaExtension}`, `--load-extension=${qaExtension}`] });
await context.setExtraHTTPHeaders({ "X-Composer-Test": "1" });
const errors = [];
try {
  await context.route("**/api/settings", route => route.fulfill({ contentType: "application/json", body: JSON.stringify({ provider: "codex" }) }));
  const app = await context.newPage();
  app.on("pageerror", error => errors.push(error.message));
  await app.goto("http://127.0.0.1:32187");
  await app.getByRole("heading", { name: "OnlineJobs.ph application" }).waitFor();
  await app.getByText("Your profile is ready", { exact: true }).waitFor();
  await app.screenshot({ path: path.join(output, "compose-desktop.png"), fullPage: true });
  assert.equal(await app.locator("body").evaluate(el => el.scrollWidth <= innerWidth), true);
  await app.getByRole("button", { name: "My profile", exact: true }).click();
  await app.getByLabel("Full name", { exact: true }).waitFor();
  assert.match(await app.getByLabel("Full name", { exact: true }).inputValue(), /Cyril/);
  await app.screenshot({ path: path.join(output, "profile-desktop.png"), fullPage: true });
  await app.getByRole("button", { name: "Browser setup", exact: false }).click();
  await app.getByLabel("Your local pairing key").waitFor();
  await app.waitForFunction(() => document.getElementById("pairing-key").value.length === 64);
  await app.screenshot({ path: path.join(output, "browser-setup.png"), fullPage: true });
  const key = await app.getByLabel("Your local pairing key").inputValue();
  const workers = context.serviceWorkers();
  const worker = workers[0] || await context.waitForEvent("serviceworker");
  const extensionId = new URL(worker.url()).host;
  const popup = await context.newPage();
  await popup.goto(`chrome-extension://${extensionId}/popup.html`);
  if (!(await popup.locator("#pairing").evaluate(el => el.open))) await popup.getByText("Pair with the local app", { exact: true }).click();
  await popup.getByLabel("Pairing key", { exact: true }).fill(key);
  await popup.getByRole("button", { name: "Save and check connection" }).click();
  try { await popup.getByRole("status").filter({ hasText: "Connected." }).waitFor({ timeout: 14000 }); }
  catch { throw new Error("Companion pairing failed: " + await popup.getByRole("status").textContent()); }
  const source = await context.newPage();
  await source.goto("http://127.0.0.1:32188/application");
  await source.bringToFront();
  const captureResult = await worker.evaluate(() => captureTab());
  assert.equal(captureResult.count, 5);
  await app.bringToFront();
  await app.getByRole("button", { name: "Other websites", exact: true }).click();
  await app.getByLabel("Answer for Application subject *", { exact: true }).waitFor();
  await app.getByLabel("Answer for Application subject *", { exact: true }).fill("CMS PARTNER — Next.js and Supabase");
  await app.getByLabel("Answer for Application message *", { exact: true }).fill("Hey! I can help with your Next.js App Router and Supabase CMS. My portfolio includes CMS and admin work on Lowrie Roofing. Happy to walk through a relevant demo and discuss your requirements.");
  await app.getByLabel("Answer for What relevant CMS project have you worked on, and how would you handle Supabase RLS?", { exact: true }).fill("Lowrie Roofing involved CMS and admin features. I would scope database access to authenticated roles and test policies against the client’s permissions model.");
  await app.getByRole("combobox", { name: "Answer for Availability", exact: true }).click();
  await app.getByRole("option", { name: "40 hours/week", exact: true }).click();
  await app.getByLabel("Answer for Portfolio URL", { exact: true }).fill("https://portfolio-cyannimazing.vercel.app/");
  const beforeGeneration = await app.locator('.answer-field textarea,.answer-field input:not([type=checkbox]),.answer-field [role=combobox]').evaluateAll(elements => elements.map(el => ({ value: el.getAttribute("role") === "combobox" ? el.dataset.value : el.value, fieldId: el.closest(".answer-field").querySelector('input[type=checkbox]').getAttribute("aria-label") })));
  await app.route("**/api/generate", route => route.fulfill({ status: 202, contentType: "application/json", body: JSON.stringify({ id: "qa-edit-lock" }) }));
  await app.route("**/api/jobs/qa-edit-lock", async route => {
    const state = await (await app.request.get("http://127.0.0.1:32187/api/state")).json();
    await route.fulfill({ contentType: "application/json", body: JSON.stringify({ state: "complete", draft: { answers: state.capture.fields.map((field, index) => ({ fieldId: field.id, value: beforeGeneration[index].value, reason: "Browser test fixture", needsInput: false })), notes: [] } }) });
  });
  await app.getByRole("button", { name: "Regenerate", exact: true }).click();
  assert.equal(await app.getByLabel("Answer for Application message *", { exact: true }).isDisabled(), true, "Answers are locked while a draft is being generated");
  assert.equal(await app.locator("#job-context").isDisabled(), true, "Job context is locked while a draft is being generated");
  await app.getByRole("status").filter({ hasText: "Application reviewed" }).waitFor();
  await app.unroute("**/api/generate");
  await app.unroute("**/api/jobs/qa-edit-lock");
  await app.screenshot({ path: path.join(output, "review-desktop.png"), fullPage: true });
  await app.getByRole("button", { name: "Fill 5 fields", exact: true }).click();
  await app.getByRole("status").filter({ hasText: "5 fields filled" }).waitFor({ timeout: 15000 });
  assert.match(await source.locator("#subject").inputValue(), /CMS PARTNER/);
  assert.equal(await source.locator("#availability-control").getAttribute("data-value"), "40");
  assert.equal(await source.evaluate(() => window.practiceSubmissionCount), 0);
  await source.screenshot({ path: path.join(output, "filled-form.png"), fullPage: true });
  await app.setViewportSize({ width: 390, height: 844 });
  await app.screenshot({ path: path.join(output, "review-mobile.png"), fullPage: true });
  assert.equal(await app.locator("body").evaluate(el => el.scrollWidth <= innerWidth), true, "No horizontal overflow on mobile");
  await app.setViewportSize({ width: 768, height: 1000 });
  await app.screenshot({ path: path.join(output, "review-tablet.png"), fullPage: true });
  assert.equal(await app.locator("body").evaluate(el => el.scrollWidth <= innerWidth), true, "No horizontal overflow on tablet");
  await app.setViewportSize({ width: 1440, height: 1000 });
  await app.getByRole("button", { name: "New application", exact: true }).click();
  await app.getByRole("button", { name: "Open the practice form", exact: false }).click();
  const practice = app.frameLocator('iframe[title="Practice application form"]');
  await practice.locator("#subject").waitFor();
  await app.getByRole("button", { name: "Capture practice form", exact: true }).click();
  await app.getByLabel("Answer for Application subject *", { exact: true }).fill("CMS PARTNER — practice answer");
  await app.getByRole("button", { name: "Fill practice form", exact: true }).click();
  assert.match(await practice.locator("#subject").inputValue(), /CMS PARTNER/);
  assert.equal(await practice.locator("body").evaluate(() => window.practiceSubmissionCount), 0);
  await app.getByRole("button", { name: "New application", exact: true }).click();
  await app.setViewportSize({ width: 390, height: 844 });
  await app.screenshot({ path: path.join(output, "compose-mobile.png"), fullPage: true });
  assert.equal(errors.length, 0, errors.join("\n"));
  console.log("PASS: Next.js profile, setup, companion pairing, capture, field review, real extension fill, local practice, no submission, and responsive layouts.");
} finally { await context.close(); await new Promise(resolve => fixture.close(resolve)); }
